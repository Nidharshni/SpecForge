use super::*;
use crate::repo::Member;

fn member(name: &str, dir: &str, description: Option<&str>, roots: &[&str]) -> Member {
    Member {
        name: name.into(),
        dir: dir.into(),
        description: description.map(Into::into),
        roots: roots.iter().map(|r| r.to_string()).collect(),
        ..Default::default()
    }
}

/// A repository in a temp dir holding `files`, with `members` as cargo metadata would list them.
fn repo(files: &[(&str, &str)], members: Vec<Member>) -> (tempfile::TempDir, Repo) {
    let dir = tempfile::tempdir().unwrap();
    for (path, text) in files {
        let path = dir.path().join(path);
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, text).unwrap();
    }
    let repo = Repo {
        root: dir.path().to_path_buf(),
        target_dir: dir.path().join("target"),
        members,
    };
    (dir, repo)
}

const DOC: &str = "//! What it is.\n";
const SHELL: &str = "# Title\n\n<!-- crate-map:begin: generated by `cargo gate crate-map` from each crate's folder and its Cargo.toml description; do not edit -->\n<!-- crate-map:end -->\n";

/// Two crates in two layers and one tool, each documented and described.
fn small() -> (tempfile::TempDir, Repo) {
    repo(
        &[
            ("crates/leaf/wire/src/lib.rs", DOC),
            ("crates/surfaces/cli/src/main.rs", DOC),
            ("tools/t/src/main.rs", DOC),
            (ARCHITECTURE, SHELL),
            (CRATES_README, SHELL),
        ],
        vec![
            member(
                "wire",
                "crates/leaf/wire",
                Some("The wire"),
                &["crates/leaf/wire/src/lib.rs"],
            ),
            member(
                "cli",
                "crates/surfaces/cli",
                Some("The binary | the terminal"),
                &["crates/surfaces/cli/src/main.rs"],
            ),
            member("t", "tools/t", Some("A tool"), &["tools/t/src/main.rs"]),
        ],
    )
}

#[test]
fn every_layer_has_a_line() {
    for layer in LAYERS {
        assert!(owns(layer).is_some(), "{layer}");
    }
}

#[test]
fn a_crate_is_drawn_in_the_layer_its_folder_names() {
    let (_dir, repo) = small();
    let map = map(&repo);
    assert!(map.problems.is_empty(), "{:?}", map.problems);
    insta::assert_snapshot!("stack", render_stack(&map));
    insta::assert_snapshot!("table", render_table(&map));
}

#[test]
fn a_crate_outside_a_layer_folder_is_named() {
    let (_dir, mut repo) = small();
    repo.members
        .push(member("flat", "crates/flat", Some("Flat"), &[]));
    repo.members
        .push(member("deep", "crates/leaf/a/b", Some("Deep"), &[]));
    repo.members
        .push(member("odd", "crates/nowhere/x", Some("Odd"), &[]));
    let problems = map(&repo).problems;
    assert_eq!(problems.len(), 3, "{problems:?}");
    assert!(
        problems[0].starts_with("`flat` is at `crates/flat`, not at `crates/<layer>/<folder>`"),
        "{}",
        problems[0]
    );
}

#[test]
fn a_member_without_a_description_or_a_crate_doc_is_named() {
    let (_dir, repo) = repo(
        &[("crates/kernel/p/src/lib.rs", "pub mod a;\n")],
        vec![member(
            "p",
            "crates/kernel/p",
            None,
            &["crates/kernel/p/src/lib.rs"],
        )],
    );
    assert_eq!(
        map(&repo).problems,
        [
            "`p` has no `description` in `crates/kernel/p/Cargo.toml`: one line saying what it owns",
            "`crates/kernel/p/src/lib.rs` opens with no `//!` crate doc saying what the crate is",
        ]
    );
}

#[test]
fn a_crate_doc_may_follow_attributes_and_plain_comments() {
    for (source, has) in [
        ("//! Doc.\npub mod a;\n", true),
        ("#![deny(clippy::print_stdout)]\n\n//! Doc.\n", true),
        (
            "// A note.\nextern crate self as x;\n//! Too late.\n",
            false,
        ),
        ("#![doc = include_str!(\"../README.md\")]\n", true),
        ("/*! Doc. */\n", true),
        ("pub mod a;\n", false),
        ("", false),
    ] {
        assert_eq!(opens_with_doc(source), has, "{source:?}");
    }
}

#[test]
fn what_the_writer_writes_the_check_accepts() {
    let (_dir, repo) = small();
    assert_eq!(
        write(&repo).unwrap(),
        ["wrote ARCHITECTURE.md", "wrote crates/README.md"]
    );
    assert_eq!(judge(&repo), Vec::<String>::new());
    assert_eq!(
        write(&repo).unwrap(),
        ["ARCHITECTURE.md is current", "crates/README.md is current"]
    );
}

#[test]
fn a_stale_block_names_its_line_and_the_fix() {
    let (_dir, mut repo) = small();
    write(&repo).unwrap();
    repo.members[0].description = Some("The guest wire".into());
    let problems = judge(&repo);
    assert_eq!(problems.len(), 1, "{problems:?}");
    assert!(
        problems[0].starts_with("ARCHITECTURE.md:") || problems[0].starts_with("crates/README.md:"),
        "{}",
        problems[0]
    );
    assert!(
        problems[0].ends_with("run `cargo gate crate-map`"),
        "{}",
        problems[0]
    );
}

#[test]
fn a_file_without_its_markers_is_named_and_nothing_is_written() {
    let (dir, repo) = small();
    std::fs::write(dir.path().join(CRATES_README), "# Crates\n").unwrap();
    assert_eq!(
        write(&repo).unwrap_err(),
        "crates/README.md holds 0 crate-map:begin and 0 crate-map:end lines; it needs one of each, in that order"
    );
    assert_eq!(
        std::fs::read_to_string(dir.path().join(ARCHITECTURE)).unwrap(),
        SHELL
    );
}

#[test]
fn a_problem_with_a_member_holds_back_the_block_comparison() {
    let (_dir, mut repo) = small();
    repo.members[0].description = None;
    assert_eq!(
        judge(&repo),
        [
            "`wire` has no `description` in `crates/leaf/wire/Cargo.toml`: one line saying what it owns"
        ]
    );
}
