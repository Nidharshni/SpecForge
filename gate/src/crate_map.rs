//! The crate map: `ARCHITECTURE.md`'s layer stack and `crates/README.md`'s table of every workspace member, rendered
//! from `cargo metadata` (each member's folder and its manifest's `description`) and this module's line per layer
//! (ADR 0091). `cargo gate crate-map` writes the two blocks. The `crate-map` check judges that the committed files
//! hold them, that every member has a one-line `description`, that every crate root opens with a `//!` doc, and that
//! every member under `crates/` is in a layer folder. The links in the two files are `doc-links`' to judge.

use std::ops::Range;

use crate::layers::{LAYERS, Place, place};
use crate::repo::{Member, Repo};

/// The file whose block is the layer stack.
pub const ARCHITECTURE: &str = "ARCHITECTURE.md";
/// The file whose block is the crate table.
pub const CRATES_README: &str = "crates/README.md";
/// The repository's model of its crates, which `xtask check-modules` holds to the manifests.
pub const MODULES_SPEC: &str = "spec/product/modules.spec";
/// The line that opens a generated block.
pub const BEGIN: &str = "<!-- crate-map:begin: generated by `cargo gate crate-map` from each crate's folder and its Cargo.toml description; do not edit -->";
/// The line that closes it.
pub const END: &str = "<!-- crate-map:end -->";

/// What a layer owns, as both blocks print it. A layer of the order without a line here is a problem the check
/// reports.
fn owns(layer: &str) -> Option<&'static str> {
    Some(match layer {
        "surfaces" => {
            "The programs: the specforge CLI, the language server, the MCP server and the package registry server. Each turns its protocol into calls on the layers below."
        }
        "adapters" => {
            "The package registry over HTTP, from both ends: its contract, the client, and the adapter behind the operations' Registry port (ADR 0010, ADR 0044)."
        }
        "app" => {
            "The user-level operations every surface shares: a typed request in, a typed outcome or a refusal out (ADR 0015)."
        }
        "session" => {
            "A project as it lives: the environment load, the compile, and the project session kept current from the file system and the editor (ADR 0047)."
        }
        "runtime" => {
            "Extensions: the host side of the protocol, the wasmtime component runtime, the installed extensions, and the SDK guests are written with (ADR 0013, ADR 0028)."
        }
        "pipeline" => {
            "From parsed files to output: import resolution, the graph build, the Registry build and its checks, formatting, migration and the export formats."
        }
        "kernel" => {
            "The .spec language and what every host crate shares: the grammar, the lexer and parser, the diagnostic, spans, symbols and the project root."
        }
        "leaf" => {
            "Crates with no SpecForge dependency but the guest wire: the wire itself, the diagnostic catalog, the coverage rule, package names and the repository root. Guests build from some of them (ADR 0050)."
        }
        _ => return None,
    })
}

/// The workspace as the map draws it.
struct Map<'a> {
    /// The top layer first; each layer's crates by folder name.
    layers: Vec<(&'static str, Vec<(&'a str, &'a Member)>)>,
    /// The members outside `crates/`, by directory.
    outside: Vec<&'a Member>,
    /// Why the map cannot be drawn as the workspace stands.
    problems: Vec<String>,
}

/// The manifest of `member`, repo-relative.
pub(crate) fn manifest_of(member: &Member) -> String {
    if member.dir.is_empty() {
        "Cargo.toml".to_string()
    } else {
        format!("{}/Cargo.toml", member.dir)
    }
}

fn map(repo: &Repo) -> Map<'_> {
    let mut layers: Vec<(&'static str, Vec<(&str, &Member)>)> = LAYERS
        .iter()
        .rev()
        .map(|layer| (*layer, Vec::new()))
        .collect();
    let mut outside = Vec::new();
    let mut problems = Vec::new();
    for layer in LAYERS {
        if owns(layer).is_none() {
            problems.push(format!(
                "the layer `{layer}` has no line in gate/src/crate_map.rs `owns`"
            ));
        }
    }
    for member in &repo.members {
        match place(&member.dir) {
            Place::Layer(index) => {
                let folder = member.dir.rsplit('/').next().unwrap_or_default();
                if let Some(row) = layers.iter_mut().find(|(l, _)| *l == LAYERS[index]) {
                    row.1.push((folder, member));
                }
            }
            Place::Outside => outside.push(member),
            Place::Misplaced => problems.push(format!(
                "`{}` is at `{}`, not at `crates/<layer>/<folder>` with one of the layers {}",
                member.name,
                member.dir,
                LAYERS.join(" ")
            )),
        }
        let manifest = manifest_of(member);
        match member.description.as_deref().map(str::trim) {
            None | Some("") => problems.push(format!(
                "`{}` has no `description` in `{manifest}`: one line saying what it owns",
                member.name
            )),
            Some(text) if text.contains('\n') => problems.push(format!(
                "`{}`'s `description` in `{manifest}` is more than one line",
                member.name
            )),
            Some(_) => {}
        }
        for root in &member.roots {
            match std::fs::read_to_string(repo.root.join(root)) {
                Ok(source) if opens_with_doc(&source) => {}
                Ok(_) => problems.push(format!(
                    "`{root}` opens with no `//!` crate doc saying what the crate is"
                )),
                Err(e) => problems.push(format!("`{root}`: {e}")),
            }
        }
    }
    for (_, crates) in &mut layers {
        crates.sort_by(|a, b| a.0.cmp(b.0));
    }
    outside.sort_by(|a, b| a.dir.cmp(&b.dir));
    Map {
        layers,
        outside,
        problems,
    }
}

/// Whether a crate root opens with its doc: a `//!` or `/*!` line, or a `#![doc …]` attribute, before its first
/// item. Blank lines, plain comments and other inner attributes may come first.
fn opens_with_doc(source: &str) -> bool {
    for line in source.lines().map(str::trim_start) {
        if line.starts_with("//!") || line.starts_with("/*!") || line.starts_with("#![doc") {
            return true;
        }
        if !(line.is_empty() || line.starts_with("//") || line.starts_with("#![")) {
            return false;
        }
    }
    false
}

/// A table cell: a `|` would end it.
fn cell(text: &str) -> String {
    text.trim().replace('|', "\\|")
}

/// `ARCHITECTURE.md`'s block: the layers, the top one first, each with what it owns and its crates' folders.
fn render_stack(map: &Map) -> String {
    let mut out = String::from("| Layer | Owns | Crates |\n|---|---|---|\n");
    for (layer, crates) in &map.layers {
        let folders: Vec<String> = crates
            .iter()
            .map(|(folder, _)| format!("[`{folder}`](crates/{layer}/{folder}/)"))
            .collect();
        out.push_str(&format!(
            "| `{layer}` | {} | {} |\n",
            cell(owns(layer).unwrap_or_default()),
            folders.join(" ")
        ));
    }
    out
}

/// `crates/README.md`'s block: per layer, the top one first, what it owns and a row per crate; then the members
/// outside `crates/`.
fn render_table(map: &Map) -> String {
    let mut out = String::new();
    for (layer, crates) in &map.layers {
        out.push_str(&format!(
            "### `{layer}`\n\n{}\n\n| Crate | Package | Owns |\n|---|---|---|\n",
            cell(owns(layer).unwrap_or_default())
        ));
        for (folder, member) in crates {
            out.push_str(&format!(
                "| [`{folder}`]({layer}/{folder}/) | `{}` | {} |\n",
                member.name,
                cell(member.description.as_deref().unwrap_or_default())
            ));
        }
        out.push('\n');
    }
    out.push_str("### Outside `crates/`\n\n| Member | Package | Owns |\n|---|---|---|\n");
    for member in &map.outside {
        let dir = if member.dir.is_empty() {
            "."
        } else {
            member.dir.as_str()
        };
        out.push_str(&format!(
            "| [`{dir}`](../{dir}/) | `{}` | {} |\n",
            member.name,
            cell(member.description.as_deref().unwrap_or_default())
        ));
    }
    out
}

/// Each file and the block the workspace gives it: a blank line, the rendering, a blank line.
fn rendered(map: &Map) -> [(&'static str, String); 2] {
    [
        (ARCHITECTURE, format!("\n{}\n", render_stack(map))),
        (CRATES_README, format!("\n{}\n", render_table(map))),
    ]
}

/// Where the block sits in `text`: from the line after its one `BEGIN` line to the start of its one `END` line.
fn block(text: &str) -> Result<Range<usize>, String> {
    let begins: Vec<usize> = text.match_indices(BEGIN).map(|(at, _)| at).collect();
    let ends: Vec<usize> = text.match_indices(END).map(|(at, _)| at).collect();
    match (begins.as_slice(), ends.as_slice()) {
        ([begin], [end]) if begin < end => {
            let after = begin + BEGIN.len();
            let start = text[after..]
                .find('\n')
                .map_or(text.len(), |n| after + n + 1);
            if start > *end {
                return Err("has its crate-map:end on the crate-map:begin line".to_string());
            }
            Ok(start..*end)
        }
        _ => Err(format!(
            "holds {} crate-map:begin and {} crate-map:end lines; it needs one of each, in that order",
            begins.len(),
            ends.len()
        )),
    }
}

/// The first line where `found` and `expected` differ: its number (from 1) and both lines (`<none>` past an end).
fn first_difference(found: &str, expected: &str) -> Option<(usize, String, String)> {
    let (mut found, mut expected) = (found.lines(), expected.lines());
    for number in 1.. {
        match (found.next(), expected.next()) {
            (None, None) => return None,
            (f, e) if f == e => continue,
            (f, e) => {
                return Some((
                    number,
                    f.unwrap_or("<none>").to_string(),
                    e.unwrap_or("<none>").to_string(),
                ));
            }
        }
    }
    None
}

/// Everything the `crate-map` check reports. First, what keeps the map from being drawn. Once there is nothing of
/// that, each file whose block is missing or differs from the rendering.
pub fn judge(repo: &Repo) -> Vec<String> {
    let map = map(repo);
    let mut problems = map.problems.clone();
    if !map.problems.is_empty() {
        return problems;
    }
    for (file, expected) in rendered(&map) {
        let text = match std::fs::read_to_string(repo.root.join(file)) {
            Ok(text) => text,
            Err(e) => {
                problems.push(format!("{file}: {e}"));
                continue;
            }
        };
        match block(&text) {
            Err(why) => problems.push(format!("{file} {why}")),
            Ok(range) => {
                if let Some((at, found, wanted)) = first_difference(&text[range.clone()], &expected)
                {
                    let line = text[..range.start].matches('\n').count() + at;
                    problems.push(format!(
                        "{file}:{line}: the crate map reads {found:?} where the workspace gives {wanted:?}; run `cargo gate crate-map`"
                    ));
                }
            }
        }
    }
    problems
}

/// `cargo gate crate-map`: rewrite both blocks from the workspace, one line per file saying whether it changed.
/// It writes nothing while the map cannot be drawn or a file lacks its markers.
pub fn write(repo: &Repo) -> Result<Vec<String>, String> {
    let map = map(repo);
    if !map.problems.is_empty() {
        return Err(map.problems.join("\n"));
    }
    let mut planned = Vec::new();
    for (file, expected) in rendered(&map) {
        let path = repo.root.join(file);
        let text = std::fs::read_to_string(&path).map_err(|e| format!("{file}: {e}"))?;
        let range = block(&text).map_err(|why| format!("{file} {why}"))?;
        let mut new = text.clone();
        new.replace_range(range, &expected);
        planned.push((file, path, new != text, new));
    }
    let mut lines = Vec::new();
    for (file, path, changed, new) in planned {
        if changed {
            std::fs::write(&path, new).map_err(|e| format!("{file}: {e}"))?;
            lines.push(format!("wrote {file}"));
        } else {
            lines.push(format!("{file} is current"));
        }
    }
    Ok(lines)
}

