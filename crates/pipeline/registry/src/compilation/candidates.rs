//! The candidate vocabulary: what extensions a host could enable declare, for the checks'
//! suggestions only (ADR 0122). It names, for each kind keyword and each field an enhancement
//! adds to another extension's kind, the extension that declares it. It decides no diagnostic
//! and no ownership (ADR 0096): a name it does not know suggests `specforge search`.

use super::populate::keyword;
use serde::{Deserialize, Serialize};
use specforge_protocol_types::ExtensionDeclaration;
use std::collections::BTreeMap;

/// The `$comment` of the written form.
const GENERATED: &str = "Generated by `cargo run -p xtask --bin revendor` from the builtins' \
pinned declarations (ADR 0122). Do not edit.";

/// What extensions a host could enable declare, for the checks' suggestions only (ADR 0122):
/// each kind keyword, and each field an enhancement adds to another extension's kind, with the
/// extension that declares it. The host hands it to the build ([`super::RegistryBuild::with_candidates`]).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct CandidateVocabulary {
    /// keyword -> extension
    kinds: BTreeMap<String, String>,
    /// kind -> field -> extension
    fields: BTreeMap<String, BTreeMap<String, String>>,
}

/// The written form, in its key order.
#[derive(Serialize, Deserialize)]
struct Written {
    #[serde(rename = "$comment", default)]
    comment: String,
    #[serde(default)]
    kinds: BTreeMap<String, String>,
    #[serde(default)]
    fields: BTreeMap<String, BTreeMap<String, String>>,
}

impl CandidateVocabulary {
    /// The vocabulary `declarations` declare: each kind under its keyword (else its name, as the
    /// registry keys it), and each enhancement field under (target kind, field name), credited to
    /// the declaration's `name()` (ADR 0096 D2). A kind's own and shared fields are not in it:
    /// they come with their kind. Err names both extensions when two declare one keyword, or one
    /// enhancement field on one kind.
    pub fn of(declarations: &[ExtensionDeclaration]) -> Result<Self, String> {
        let mut vocabulary = Self::default();
        for declaration in declarations {
            let extension = declaration.name();
            for kind in &declaration.entities {
                let word = keyword(kind);
                if let Some(first) = vocabulary
                    .kinds
                    .insert(word.to_string(), extension.to_string())
                {
                    return Err(format!(
                        "{first} and {extension} both declare the kind keyword '{word}'"
                    ));
                }
            }
            for enhancement in &declaration.enhancements {
                for field in &enhancement.fields {
                    let by_field = vocabulary
                        .fields
                        .entry(enhancement.target_kind.clone())
                        .or_default();
                    if let Some(first) = by_field.insert(field.name.clone(), extension.to_string())
                    {
                        return Err(format!(
                            "{first} and {extension} both add the field '{}' to '{}'",
                            field.name, enhancement.target_kind
                        ));
                    }
                }
            }
        }
        Ok(vocabulary)
    }

    /// The vocabulary a written form says (`to_json`); unreadable text is the empty vocabulary,
    /// so every suggestion falls back to `specforge search` (the spec's fallback). Unknown keys
    /// are ignored.
    pub fn from_json(text: &str) -> Self {
        match serde_json::from_str::<Written>(text) {
            Ok(written) => Self {
                kinds: written.kinds,
                fields: written.fields,
            },
            Err(_) => Self::default(),
        }
    }

    /// `{"$comment": GENERATED, "kinds": {..}, "fields": {kind: {field: ext}}}`, keys sorted,
    /// pretty-printed, with a trailing newline.
    pub fn to_json(&self) -> String {
        let written = Written {
            comment: GENERATED.to_string(),
            kinds: self.kinds.clone(),
            fields: self.fields.clone(),
        };
        let mut text =
            serde_json::to_string_pretty(&written).expect("a map of strings always serializes");
        text.push('\n');
        text
    }

    /// The extension that declares the kind written with `keyword`.
    pub fn kind_owner(&self, keyword: &str) -> Option<&str> {
        self.kinds.get(keyword).map(String::as_str)
    }

    /// The extension whose enhancement adds `field` to `kind`.
    pub fn field_owner(&self, kind: &str, field: &str) -> Option<&str> {
        self.fields
            .get(kind)
            .and_then(|fields| fields.get(field))
            .map(String::as_str)
    }

    /// Whether it names nothing.
    pub fn is_empty(&self) -> bool {
        self.kinds.is_empty() && self.fields.is_empty()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use specforge_extension_sdk::prelude::*;

    fn declare(name: &str, f: impl FnOnce(&mut ContributionsBuilder)) -> ExtensionDeclaration {
        let mut c = ContributionsBuilder::new(ExtensionMeta::new(name, "1.0.0"));
        f(&mut c);
        c.declaration()
    }

    fn gizmo_and_widget() -> Vec<ExtensionDeclaration> {
        let a = declare("@x/a", |c| {
            c.kind("Gizmo", |k| {
                k.keyword("gizmo");
                k.field("size", |f| {
                    f.field_type(FieldType::String);
                });
            });
            c.enhance("widget", |e| {
                e.field("colour", |f| {
                    f.field_type(FieldType::String);
                });
            });
        });
        let b = declare("@x/b", |c| {
            c.kind("Widget", |_| {});
        });
        vec![a, b]
    }

    #[test]
    fn of_maps_each_kind_and_enhancement_field_to_its_declarer() {
        let v = CandidateVocabulary::of(&gizmo_and_widget()).unwrap();
        assert_eq!(v.kind_owner("gizmo"), Some("@x/a"));
        assert_eq!(v.kind_owner("Widget"), Some("@x/b"));
        assert_eq!(v.field_owner("widget", "colour"), Some("@x/a"));
        assert_eq!(v.field_owner("gizmo", "size"), None);
        assert_eq!(v.kind_owner("xyzzy"), None);
        assert!(!v.is_empty());
    }

    #[test]
    fn two_candidates_declaring_one_keyword_are_refused() {
        let mut declarations = gizmo_and_widget();
        declarations.push(declare("@x/c", |c| {
            c.kind("Other", |k| {
                k.keyword("gizmo");
            });
        }));
        let err = CandidateVocabulary::of(&declarations).unwrap_err();
        assert!(
            err.contains("@x/a") && err.contains("@x/c") && err.contains("'gizmo'"),
            "{err}"
        );
    }

    #[test]
    fn two_candidates_adding_one_field_to_one_kind_are_refused() {
        let mut declarations = gizmo_and_widget();
        declarations.push(declare("@x/c", |c| {
            c.enhance("widget", |e| {
                e.field("colour", |f| {
                    f.field_type(FieldType::String);
                });
            });
        }));
        let err = CandidateVocabulary::of(&declarations).unwrap_err();
        assert!(
            err.contains("@x/a") && err.contains("@x/c") && err.contains("'colour'"),
            "{err}"
        );
    }

    #[test]
    fn the_written_form_reads_back() {
        let v = CandidateVocabulary::of(&gizmo_and_widget()).unwrap();
        let text = v.to_json();
        assert!(text.starts_with("{\n  \"$comment\": "), "{text}");
        assert!(text.ends_with("}\n"), "{text}");
        assert!(
            text.find("\"Widget\"").unwrap() < text.find("\"gizmo\"").unwrap(),
            "sorted: {text}"
        );
        assert_eq!(CandidateVocabulary::from_json(&text), v);
        assert_eq!(
            CandidateVocabulary::from_json(&CandidateVocabulary::default().to_json()),
            CandidateVocabulary::default()
        );
    }

    #[test]
    fn a_malformed_vocabulary_is_empty_so_suggestions_fall_back_to_search() {
        let v = CandidateVocabulary::from_json("{not json");
        assert_eq!(v.kind_owner("feature"), None);
        assert!(v.is_empty());
    }
}
